/**
 * Contact details used by the links and email form.
 */
const contactConfig = {
  email: "abdullahishefiu99@gmail.com",
  whatsappNumber: "2348145892973",
};

const LANGUAGE_STORAGE_KEY = "abdullahi-portfolio-language";

const languageToggle = document.querySelector("[data-language-toggle]");
const languageButtons = document.querySelectorAll("[data-lang]");
const contactForm = document.querySelector("#contact-form");
const currentYear = document.querySelector("#current-year");

function getInitialLanguage() {
  const savedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY);

  if (savedLanguage === "en" || savedLanguage === "ar") {
    return savedLanguage;
  }

  return "en";
}

function applyLanguage(language) {
  const dictionary = translations[language];

  if (!dictionary) {
    return;
  }

  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translatedText = dictionary[key];

    if (typeof translatedText === "string") {
      element.textContent = translatedText;
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.setAttribute("aria-current", isActive ? "true" : "false");
  });

  languageToggle.setAttribute(
    "aria-label",
    language === "en" ? "Switch to Arabic" : "التبديل إلى الإنجليزية",
  );

  languageToggle.setAttribute("lang", language === "en" ? "ar" : "en");

  document.title =
    language === "ar"
      ? "عبد الله — مترجم ومستنسخ إنجليزي وعربي"
      : "Abdullahi — English ⇄ Arabic Translator & Transcriber";

  const description = document.querySelector('meta[name="description"]');

  if (description) {
    description.content =
      language === "ar"
        ? "خدمات ترجمة ونسخ احترافية بين الإنجليزية والعربية في مجالات التعليم والأعمال والمحتوى العام."
        : "Professional English–Arabic translation and transcription services in education, business, and general content.";
  }

  const ogLocale = document.querySelector('meta[property="og:locale"]');

  if (ogLocale) {
    ogLocale.content = language === "ar" ? "ar_NG" : "en_NG";
  }

  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

function toggleLanguage() {
  const currentLanguage = document.documentElement.lang;
  applyLanguage(currentLanguage === "en" ? "ar" : "en");
}

function configureContactLinks() {
  const emailLink = document.querySelector('a[href^="mailto:"]');
  const whatsappLink = document.querySelector('a[href^="https://wa.me/"]');

  if (emailLink) {
    emailLink.href = `mailto:${contactConfig.email}`;
  }

  if (whatsappLink) {
    whatsappLink.href = `https://wa.me/${contactConfig.whatsappNumber}`;
  }

}

function openEmailApp(event) {
  event.preventDefault();

  const formData = new FormData(contactForm);
  const senderName = formData.get("name").trim();
  const senderEmail = formData.get("email").trim();
  const projectDetails = formData.get("message").trim();
  const language = document.documentElement.lang;

  const subject =
    language === "ar"
      ? `طلب مشروع ترجمة أو نسخ من ${senderName}`
      : `Translation / transcription inquiry from ${senderName}`;

  const body =
    language === "ar"
      ? `الاسم: ${senderName}\nالبريد الإلكتروني: ${senderEmail}\n\nتفاصيل المشروع:\n${projectDetails}`
      : `Name: ${senderName}\nEmail: ${senderEmail}\n\nProject details:\n${projectDetails}`;

  const mailtoUrl =
    `mailto:${encodeURIComponent(contactConfig.email)}` +
    `?subject=${encodeURIComponent(subject)}` +
    `&body=${encodeURIComponent(body)}`;

  window.location.href = mailtoUrl;
}

languageToggle?.addEventListener("click", toggleLanguage);
contactForm?.addEventListener("submit", openEmailApp);

if (currentYear) {
  currentYear.textContent = new Date().getFullYear();
}

configureContactLinks();
applyLanguage(getInitialLanguage());
